#!/usr/bin/env python

import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
TEX  = os.path.join(HERE, "base_model_card.tex")
JSON = os.path.join(HERE, "base_eval.json")
BEGIN, END = "%% <<RESULTS_BEGIN>>", "%% <<RESULTS_END>>"

def esc(x):
    return str(x).replace("%", "\\%").replace("_", "\\_")

def build_block():
    if not os.path.exists(JSON):
        return (f"{BEGIN}\n\\emph{{No \\code{{base\\_eval.json}} yet --- run \\code{{eval\\_base\\_flu.py}}, "
                f"then \\code{{build\\_base\\_card.py}}.}}\n{END}")
    data = json.load(open(JSON))
    s = data["summary"]
    eps = data.get("episodes", [])
    dtr = [e["decisions_to_reach"] for e in eps if e.get("decisions_to_reach") is not None]
    rng = f" (median {s.get('median_decisions_to_reach')}; range {min(dtr)}--{max(dtr)})" if dtr else ""
    er = s.get("end_reasons", {})
    rows = [
        ("Episodes", s.get("episodes")),
        ("Success rate", f"{s.get('successes')}/{s.get('episodes')} = {round(s.get('success_rate', 0)*100)}%"),
        ("Mean decisions to reach gate", f"{s.get('mean_decisions_to_reach')}{rng}"),
        ("Mean min distance (m)", s.get("mean_min_d")),
        ("Mean final distance (m)", s.get("mean_final_d")),
        ("End reasons (SUCCESS / FALL / TIMEOUT)",
         f"{er.get('SUCCESS', 0)} / {er.get('FALL', 0)} / {er.get('TIMEOUT', 0)}"),
    ]
    body = "\n".join(f"{esc(k)} & {esc(v)}\\\\" for k, v in rows)
    ckpt = os.path.basename(s.get("model", "")).replace("_", "\\_")
    return (f"{BEGIN} (auto-generated by build_base_card.py from base_eval.json -- do not hand-edit)\n"
            "\\begin{center}\n\\begin{tabular}{ll}\n\\hline\nMetric & Value\\\\\n\\hline\n"
            f"{body}\n\\hline\n\\end{{tabular}}\n\\end{{center}}\n"
            f"No falls or timeouts unless the table says otherwise. Evaluated on \\code{{{ckpt}}} "
            f"({esc(s.get('date', ''))}).\n{END}")

def main():
    tex = open(TEX).read()
    if BEGIN not in tex or END not in tex:
        sys.exit(f"markers {BEGIN}/{END} not found in {TEX}")
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: build_block(), tex, flags=re.S)
    open(TEX, "w").write(new)
    for i in (1, 2):
        r = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "base_model_card.tex"],
                           cwd=HERE, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if r.returncode != 0:
            sys.exit(f"pdflatex pass {i} failed -- run it manually in {HERE} to see the error")
    for ext in (".aux", ".log"):
        try: os.remove(os.path.join(HERE, "base_model_card" + ext))
        except FileNotFoundError: pass
    print(f"base_model_card.pdf rebuilt from base_eval.json ({'present' if os.path.exists(JSON) else 'MISSING'})")

if __name__ == "__main__":
    main()
